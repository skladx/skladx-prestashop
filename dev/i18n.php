/*
 * Development tool: builds translations/sk.php (PrestaShop module translation
 * format) from the Slovak dictionary dev/sk.php.
 *
 *   php dev/i18n.php           write translations/sk.php
 *   php dev/i18n.php --check   only report strings without a translation (exit 1)
 *
 * Extracted: T::__('…') and T::f('…') and $this->l('…') in PHP files (source
 * key "skladx"), {l s='…' mod='skladx'} in templates (source key = template
 * file name).
 */
if (PHP_SAPI !== 'cli') {
    exit(1);
}

$root = dirname(__DIR__);

/**
 * @return array<string, list<string>> source => strings
 */
function skladx_extract(string $root): array
{
    $found = [];
    $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root, FilesystemIterator::SKIP_DOTS));

    foreach ($iterator as $file) {
        $path = (string) $file;
        $relative = substr($path, strlen($root) + 1);

        if (preg_match('#^(vendor|tests|dev|translations)/#', $relative)) {
            continue;
        }

        $content = (string) file_get_contents($path);

        if (str_ends_with($path, '.php')) {
            preg_match_all("/(?:T::(?:__|f)|\\\$this->l)\\(\\s*'((?:[^'\\\\]|\\\\.)*)'/", $content, $matches);

            foreach ($matches[1] as $string) {
                $found['skladx'][] = str_replace("\\'", "'", $string);
            }
        } elseif (str_ends_with($path, '.tpl')) {
            preg_match_all("/\\{l\\s+s='((?:[^'\\\\]|\\\\.)*)'[^}]*mod='skladx'[^}]*\\}/", $content, $matches);

            foreach ($matches[1] as $string) {
                $found[strtolower(basename($path, '.tpl'))][] = $string;
            }
        }
    }

    return array_map(static fn (array $strings): array => array_values(array_unique($strings)), $found);
}

$dictionary = require __DIR__ . '/sk.php';
$found = skladx_extract($root);
$missing = [];
$lines = [];

ksort($found);

foreach ($found as $source => $strings) {
    sort($strings);

    foreach ($strings as $string) {
        if (!isset($dictionary[$string]) || $dictionary[$string] === '') {
            $missing[$string] = true;
            continue;
        }

        $key = '<{skladx}prestashop>' . $source . '_' . md5((string) preg_replace("/\\\\*'/", "\\'", $string));
        $lines[] = '$_MODULE[\'' . $key . '\'] = \'' . str_replace(['\\', "'"], ['\\\\', "\\'"], $dictionary[$string]) . '\';';
    }
}

if (in_array('--check', $argv, true)) {
    foreach (array_keys($missing) as $string) {
        fwrite(STDERR, 'missing: ' . $string . "\n");
    }

    exit($missing === [] ? 0 : 1);
}

$header = <<<'PHP'
<?php
/**
 * SkladX for PrestaShop – Slovak translation (generated by dev/i18n.php from dev/sk.php).
 *
 * @author    SkladX <info@skladx.sk>
 * @copyright SkladX
 * @license   https://www.gnu.org/licenses/gpl-2.0.html GPL-2.0-or-later
 */
global $_MODULE;
$_MODULE = [];

PHP;

file_put_contents($root . '/translations/sk.php', $header . implode("\n", $lines) . "\n");
fwrite(STDOUT, sprintf("translations/sk.php: %d strings, %d missing\n", count($lines), count($missing)));

foreach (array_keys($missing) as $string) {
    fwrite(STDOUT, 'missing: ' . $string . "\n");
}
